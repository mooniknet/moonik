  function safeGet(key) {
    try { return localStorage.getItem(key); } catch (e) { return null; }
  }
  function safeSet(key, value) {
    try { localStorage.setItem(key, value); } catch (e) {}
  }

  function detectLang() {
    var saved = safeGet("moonik-lang");
    if (saved === "ko" || saved === "en") return saved;
    var nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    return nav.indexOf("ko") === 0 ? "ko" : "en";
  }

  function applyLang(lang) {
    var d = dict[lang] || dict.en;
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (d[key] !== undefined) el.innerHTML = d[key];
    });

    document.querySelectorAll("[data-img-ko][data-img-en]").forEach(function (img) {
      var src = img.getAttribute(lang === "ko" ? "data-img-ko" : "data-img-en");
      var alt = img.getAttribute(lang === "ko" ? "data-alt-ko" : "data-alt-en");
      if (src) img.setAttribute("src", src);
      if (alt) img.setAttribute("alt", alt);
    });

    var titleEl = document.querySelector("title[data-i18n-title]");
    if (titleEl) {
      var titleKey = titleEl.getAttribute("data-i18n-title");
      if (d[titleKey] !== undefined) document.title = d[titleKey];
    }

    var metaEl = document.querySelector('meta[name="description"][data-i18n-content]');
    if (metaEl) {
      var metaKey = metaEl.getAttribute("data-i18n-content");
      if (d[metaKey] !== undefined) metaEl.setAttribute("content", d[metaKey]);
    }

    var toggle = document.getElementById("lang-toggle");
    if (toggle) toggle.textContent = lang === "ko" ? "EN" : "한국어";

    safeSet("moonik-lang", lang);
  }

  window.moonikLang = {
    apply: applyLang,
    toggle: function () {
      var cur = document.documentElement.lang === "ko" ? "ko" : "en";
      applyLang(cur === "ko" ? "en" : "ko");
    }
  };

  window.moonikNav = {
    toggle: function () {
      var links = document.querySelector(".nav-links");
      if (links) links.classList.toggle("open");
    },
    close: function () {
      var links = document.querySelector(".nav-links");
      if (links) links.classList.remove("open");
    }
  };

  document.addEventListener("DOMContentLoaded", function () {
    document.querySelectorAll(".nav-links a").forEach(function (a) {
      a.addEventListener("click", window.moonikNav.close);
    });
  });

  applyLang(detectLang());
